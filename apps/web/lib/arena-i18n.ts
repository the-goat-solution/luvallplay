const DICT: Record<Lang, Dict> = { en: EN, vi: VI };
export type ArenaKey = keyof typeof EN;

export function at(lang: Lang, key: ArenaKey, vars?: Record<string, string | number>): string {
  let s: string = DICT[lang][key] ?? EN[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function useArenaT() {
  const { lang } = useLanguage();
  const t = useCallback((key: ArenaKey, vars?: Record<string, string | number>) => at(lang, key, vars), [lang]);
  return { lang, t };
}
