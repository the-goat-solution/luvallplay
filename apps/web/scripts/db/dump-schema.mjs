// Schema-only description of the public schema, built from the Postgres
// catalog in a stable order: tables (columns in their real order, defaults,
// constraints), indexes, then sequences, functions and triggers. No data.
//
// Used by scripts/schema-dump.mjs (the committed production dump) and by the
// schema drift check (tests/schema-drift.test.ts, test plan §3.3), so both
// sides of the comparison are produced by exactly the same code.

export const DUMP_HEADER = "-- Schema of the public schema (no data). Generated by scripts/schema-dump.mjs.";

/** @param {{ query: (sql: string, params?: unknown[]) => Promise<{ rows: any[] }> }} c */
export async function dumpSchema(c) {
  const tables = (
    await c.query(`SELECT c.oid, c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = 'public' AND c.relkind IN ('r','p') ORDER BY c.relname`)
  ).rows;
  const out = [DUMP_HEADER, ""];
  for (const t of tables) {
    const cols = (
      await c.query(
        `SELECT a.attname, format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull,
          pg_get_expr(d.adbin, d.adrelid) AS def
        FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum`,
        [t.oid],
      )
    ).rows;
    const cons = (
      await c.query(`SELECT conname, pg_get_constraintdef(oid) AS def FROM pg_constraint WHERE conrelid = $1 ORDER BY contype, conname`, [t.oid])
    ).rows;
    const lines = cols.map((col) => `  ${col.attname} ${col.type}${col.def ? ` DEFAULT ${col.def}` : ""}${col.attnotnull ? " NOT NULL" : ""}`);
    for (const k of cons) lines.push(`  CONSTRAINT ${k.conname} ${k.def}`);
    out.push(`CREATE TABLE ${t.relname} (\n${lines.join(",\n")}\n);`);
    const idx = (
      await c.query(
        `SELECT pg_get_indexdef(i.indexrelid) AS def FROM pg_index i JOIN pg_class ic ON ic.oid = i.indexrelid
        WHERE i.indrelid = $1 AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conindid = i.indexrelid) ORDER BY ic.relname`,
        [t.oid],
      )
    ).rows;
    for (const i of idx) out.push(`${i.def};`);
    out.push("");
  }
  // Sequences: type, owning column, and any non-default setting.
  const seqs = (
    await c.query(`SELECT s.relname, format_type(q.seqtypid, NULL) AS type, q.seqincrement::text AS inc, q.seqstart::text AS start,
        q.seqmin::text AS min, q.seqmax::text AS max, q.seqcache::text AS cache, q.seqcycle AS cycle,
        t.relname AS owner_table, a.attname AS owner_column
      FROM pg_class s
      JOIN pg_namespace n ON n.oid = s.relnamespace
      JOIN pg_sequence q ON q.seqrelid = s.oid
      LEFT JOIN pg_depend d ON d.objid = s.oid AND d.classid = 'pg_class'::regclass AND d.refclassid = 'pg_class'::regclass AND d.deptype IN ('a','i')
      LEFT JOIN pg_class t ON t.oid = d.refobjid
      LEFT JOIN pg_attribute a ON a.attrelid = d.refobjid AND a.attnum = d.refobjsubid
      WHERE n.nspname = 'public' AND s.relkind = 'S'
      ORDER BY s.relname`)
  ).rows;
  if (seqs.length) out.push("-- Sequences");
  const typeMax = { smallint: "32767", integer: "2147483647", bigint: "9223372036854775807" };
  for (const s of seqs) {
    const extra = [];
    if (s.inc !== "1") extra.push(`INCREMENT BY ${s.inc}`);
    if (s.min !== "1") extra.push(`MINVALUE ${s.min}`);
    if (s.max !== typeMax[s.type]) extra.push(`MAXVALUE ${s.max}`);
    if (s.start !== "1") extra.push(`START WITH ${s.start}`);
    if (s.cache !== "1") extra.push(`CACHE ${s.cache}`);
    if (s.cycle) extra.push("CYCLE");
    const owned = s.owner_table ? ` OWNED BY ${s.owner_table}.${s.owner_column}` : "";
    out.push(`CREATE SEQUENCE ${s.relname} AS ${s.type}${extra.length ? ` ${extra.join(" ")}` : ""}${owned};`);
  }
  out.push("");
  // Functions and triggers (Phase 3 step 3 added the first ones). The
  // sections only appear when there is something in them, so dumps taken
  // before then are unchanged.
  const fns = (
    await c.query(`SELECT p.proname, pg_get_functiondef(p.oid) AS def FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
      WHERE n.nspname = 'public' AND p.prokind = 'f'
        AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e')
      ORDER BY p.proname, p.oid`)
  ).rows;
  if (fns.length) {
    out.push("-- Functions");
    for (const f of fns) out.push(`${f.def.trimEnd()};`);
    out.push("");
  }
  const trgs = (
    await c.query(`SELECT pg_get_triggerdef(t.oid) AS def FROM pg_trigger t JOIN pg_class r ON r.oid = t.tgrelid JOIN pg_namespace n ON n.oid = r.relnamespace
      WHERE n.nspname = 'public' AND NOT t.tgisinternal ORDER BY r.relname, t.tgname`)
  ).rows;
  if (trgs.length) {
    out.push("-- Triggers");
    for (const t of trgs) out.push(`${t.def};`);
    out.push("");
  }
  // Row-level security (Phase 3 step 10): which tables have it, whether it
  // is forced on the owner too, and every policy. Only when there is some.
  const rls = (
    await c.query(`SELECT r.relname, r.relforcerowsecurity AS forced FROM pg_class r JOIN pg_namespace n ON n.oid = r.relnamespace
      WHERE n.nspname = 'public' AND r.relkind = 'r' AND r.relrowsecurity ORDER BY r.relname`)
  ).rows;
  const policies = (
    await c.query(`SELECT tablename, policyname, permissive, roles::text AS roles, cmd, qual, with_check FROM pg_policies WHERE schemaname = 'public' ORDER BY tablename, policyname`)
  ).rows;
  if (rls.length || policies.length) {
    out.push("-- Row-level security");
    for (const r of rls) out.push(`ALTER TABLE ${r.relname} ENABLE${r.forced ? " AND FORCE" : ""} ROW LEVEL SECURITY;`);
    for (const p of policies) {
      out.push(`POLICY ${p.policyname} ON ${p.tablename} (${p.permissive}) FOR ${p.cmd} TO ${p.roles} USING (${p.qual ?? ""}) WITH CHECK (${p.with_check ?? ""});`);
    }
    out.push("");
  }
  return out.join("\n");
}

/** A dump without its functions and triggers: what a Drizzle schema can describe. */
export function tablesOnly(dump) {
  const i = dump.indexOf("\n-- Functions\n");
  const j = dump.indexOf("\n-- Triggers\n");
  const cut = [i, j].filter((x) => x >= 0);
  return cut.length ? `${dump.slice(0, Math.min(...cut)).trimEnd()}\n` : dump;
}

/** Line diff of two dumps (empty array = no drift). */
export function schemaDiff(expected, actual) {
  const a = expected.trimEnd().split("\n");
  const b = actual.trimEnd().split("\n");
  const setA = new Set(a);
  const setB = new Set(b);
  const out = [];
  for (const line of a) if (!setB.has(line)) out.push(`- ${line}`);
  for (const line of b) if (!setA.has(line)) out.push(`+ ${line}`);
  // Same lines in a different order (e.g. column order) is drift too.
  if (out.length === 0 && a.join("\n") !== b.join("\n")) out.push("~ same statements in a different order");
  return out;
}
