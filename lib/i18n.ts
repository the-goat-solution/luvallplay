export function t(
  lang: Lang,
  key: I18nKey,
  vars?: Record<string, string | number>,
): string {
  let s: string = I18N[lang][key] ?? I18N.en[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      s = s.split(`{${k}}`).join(String(v));
    });
  }
  return s;
}
