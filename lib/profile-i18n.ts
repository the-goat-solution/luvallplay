const DICT: Record<Lang, Dict> = { en: EN, vi: VI };

export type ProfileKey = keyof typeof EN;

export function pt(lang: Lang, key: ProfileKey, vars?: Record<string, string | number>): string {
  let s: string = DICT[lang][key] ?? EN[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function useProfileT() {
  const { lang } = useLanguage();
  const tr = useCallback((key: ProfileKey, vars?: Record<string, string | number>) => pt(lang, key, vars), [lang]);
  return { lang, tr };
}
