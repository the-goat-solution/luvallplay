// Schema-only dump built from the Postgres catalog: tables, columns,
// defaults, constraints and indexes, in a stable order. No data.
// Works where pg_dump can't connect (DB_DRIVER=neon-ws, see db-client.mjs).
// Used for the schema drift check (test plan §3.3).
//
//   POSTGRES_URL=... node scripts/schema-dump.mjs > docs/schema/<name>.sql
import { dbClient } from "./db-client.mjs";

const url = process.env.POSTGRES_URL;
if (!url) {
  console.error("POSTGRES_URL is not set.");
  process.exit(2);
}
const c = await dbClient(url, "schema-dump");
await c.connect();
try {
  await c.query("BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY");
  const tables = (await c.query(`SELECT c.oid, c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind IN ('r','p') ORDER BY c.relname`)).rows;
  const out = ["-- Schema of the public schema (no data). Generated by scripts/schema-dump.mjs.", ""];
  for (const t of tables) {
    const cols = (await c.query(`SELECT a.attname, format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull,
        pg_get_expr(d.adbin, d.adrelid) AS def
      FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
      WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum`, [t.oid])).rows;
    const cons = (await c.query(`SELECT conname, pg_get_constraintdef(oid) AS def FROM pg_constraint WHERE conrelid = $1 ORDER BY contype, conname`, [t.oid])).rows;
    const lines = cols.map((col) => `  ${col.attname} ${col.type}${col.def ? ` DEFAULT ${col.def}` : ""}${col.attnotnull ? " NOT NULL" : ""}`);
    for (const k of cons) lines.push(`  CONSTRAINT ${k.conname} ${k.def}`);
    out.push(`CREATE TABLE ${t.relname} (\n${lines.join(",\n")}\n);`);
    const idx = (await c.query(`SELECT pg_get_indexdef(i.indexrelid) AS def FROM pg_index i JOIN pg_class ic ON ic.oid = i.indexrelid
      WHERE i.indrelid = $1 AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conindid = i.indexrelid) ORDER BY ic.relname`, [t.oid])).rows;
    for (const i of idx) out.push(`${i.def};`);
    out.push("");
  }
  await c.query("ROLLBACK");
  process.stdout.write(out.join("\n"));
} finally {
  await c.end();
}
